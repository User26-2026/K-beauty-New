"""Курсы валют и множитель импорта — в одном месте.

Курс меняется, и когда он зашит в каждом инструменте отдельно, отчеты
начинают расходиться между собой. Правим здесь, пересчитываются все.

KRW_RUB подтвержден по инвойсу на контейнер: остаток 279 783 740 вон
поставщик пересчитал в 194 294,26 доллара, это 1440 вон за доллар.
"""

KRW_RUB = 0.062       # рублей за одну вону
USD_RUB = 87.0        # рублей за доллар
IMPORT_MULTIPLIER = 1.4   # логистика, пошлина и приемка при пересчете прайсов


def rub_per_unit(currency, imported=True):
    """Во сколько рублей обходится одна единица валюты прайса.

    Для корейской закупки сверху идет множитель импорта: логистика,
    пошлина и приемка. Для России и Киргизии его нет — там цена уже
    внутренняя, а Киргизию мы вообще держим как ориентир, а не как канал.
    """
    if currency == "KRW":
        return KRW_RUB * (IMPORT_MULTIPLIER if imported else 1)
    if currency == "USD":
        return USD_RUB
    return 1.0
