def make_table(rows, col_widths, header=True, repeat_rows=1):
    data = []
    for r_i, row in enumerate(rows):
        style = styles["TableHeadRu"] if header and r_i == 0 else styles["TableRu"]
        data.append([p(str(c).replace("\n", "<br/>"), style) for c in row])

    table = Table(data, colWidths=col_widths, repeatRows=repeat_rows if header else 0)
    ts = [
        ("GRID", (0, 0), (-1, -1), 0.35, colors.HexColor("#d8e0ea")),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 5),
        ("RIGHTPADDING", (0, 0), (-1, -1), 5),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]
    if header:
        ts += [
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#17324d")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ]
    for i in range(1 if header else 0, len(rows)):
        if i % 2 == 0:
            ts.append(("BACKGROUND", (0, i), (-1, i), colors.HexColor("#f6f8fb")))
    table.setStyle(TableStyle(ts))
    return table


