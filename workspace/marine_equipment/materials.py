#!/usr/bin/env python3
"""Материал позиций, подтвержденный владельцем.

В учете материал проставлен у 33 позиций из 271, остальное определялось
по названию. Там, где материал назван нам прямо, он записывается сюда и
бьет любое определение по названию: это факт, а не догадка.

Материал решает две вещи сразу. Первая — цена лома: бронза 745 руб за
килограмм, сталь 19, разница в 39 раз. И цена продажи от него же:
закупочная считается как лом на 2,5. Вторая — цена продажи: у
конкурента стальная задвижка Ду200 стоит 40 000 против 150 000 за
бронзовую, то есть втрое дешевле. Ошибиться в материале дороже, чем
ошибиться в количестве.

Значения те же, что возвращает material(): «бронза/латунь», «латунь»,
«бронза», «сталь», «нержавейка», «титан».
"""

import re

# По номеру чертежа — самый надежный ключ, наименования в файлах разные.
BY_DRAWING = {
    # Задвижки (желтая) ок. крышек, Склад 3, 13 шт, цены нет.
    # Подтверждено владельцем 13.10.2026.
    "544-03.046": "сталь",
}

# По названию, где материал известен для всей группы целиком.
BY_NAME = [
    # Головки воздушные (воздушно-квадратные поплавковые) — латунь.
    # Подтверждено владельцем 13.10.2026. Это 4 позиции, 36 шт, 339 кг.
    (re.compile(r"головк\w*\s+воздушн", re.I), "латунь"),
    # Грибки АМГ — это не латунь: АМг алюминиево-магниевый сплав, по
    # приемке 260 руб за кг против 635. 3 позиции, 7 шт, 23 кг.
    # ПО НАЗВАНИЮ, владельцем отдельно не подтверждено.
    (re.compile(r"\bамг\b", re.I), "алюминий"),
]


def norm_draw(value):
    """Чертеж без пробелов и в нижнем регистре: в файлах пишут по-разному."""
    return re.sub(r"\s+", "", str(value or "")).lower()


_BY_DRAWING = {norm_draw(k): v for k, v in BY_DRAWING.items()}


def known(name="", drawing=""):
    """Подтвержденный материал или None, если подтверждения нет."""
    d = _BY_DRAWING.get(norm_draw(drawing))
    if d:
        return d
    for rx, m in BY_NAME:
        if rx.search(name or ""):
            return m
    return None
