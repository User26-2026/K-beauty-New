def head(ws, row, ncols, height=30):
    for c in range(1, ncols + 1):
        cell = ws.cell(row=row, column=c)
        cell.fill = HEAD_FILL
        cell.font = HEAD_FONT
        cell.alignment = Alignment(vertical="center", wrap_text=True)
        cell.border = BORDER
    ws.row_dimensions[row].height = height


def widths(ws, values):
    for i, w in enumerate(values, start=1):
        ws.column_dimensions[get_column_letter(i)].width = w


def main():
    wb = Workbook()
    ws = wb.active
    ws.title = "План по шагам"
    ws["A1"] = "Отгрузка арматуры в Петербург: что делать по порядку"
    ws["A1"].font = TITLE
    ws["A2"] = ("Пункты 1-4 — критический путь, без них контейнер "
                "заказывать рано. Этапы 2 и 3 можно вести параллельно с "
                "первым, тогда вся подготовка укладывается в неделю.")
    ws["A2"].font = NOTE

    row = 4
    ws.cell(row=row, column=1, value="Коротко о сделке").font = SUB
    row += 1
    for label, value in FACTS:
        ws.cell(row=row, column=1, value=label).font = BOLD
        cell = ws.cell(row=row, column=2, value=value)
        cell.font = BASE
        cell.alignment = Alignment(wrap_text=True, vertical="top")
        row += 1

    row += 1
    cols = ["№", "Что сделать", "Кто", "Срок", "Что на выходе",
            "Что встанет без этого", "Готово"]
    for i, h in enumerate(cols, start=1):
        ws.cell(row=row, column=i, value=h)
    head(ws, row, len(cols), height=34)
    header_row = row

    n = 0
    for stage, steps in PLAN:
        row += 1
        ws.cell(row=row, column=1, value=stage)
        for c in range(1, len(cols) + 1):
            cell = ws.cell(row=row, column=c)
            cell.fill = STAGE_FILL
            cell.font = SUB
            cell.border = BORDER
        ws.row_dimensions[row].height = 22
        for what, who, when, result, blocks in steps:
            n += 1
            row += 1
            for i, v in enumerate([n, what, who, when, result, blocks, ""],
                                  start=1):
                cell = ws.cell(row=row, column=i, value=v)
                cell.font = BOLD if i == 1 else BASE
                cell.border = BORDER
                cell.alignment = Alignment(vertical="top",
                                           wrap_text=(i in (2, 5, 6)))
            if n <= 4:
                ws.cell(row=row, column=1).fill = STOP_FILL
                ws.cell(row=row, column=2).fill = NOW_FILL
            ws.cell(row=row, column=7).fill = DONE_FILL
            ws.row_dimensions[row].height = max(
                32, 13 * (len(what) // 70 + 1))

    last = row
    ws.auto_filter.ref = f"A{header_row}:G{last}"
    ws.freeze_panes = f"A{header_row + 1}"

    row += 2
    ws.cell(row=row, column=1, value="Почему порядок именно такой").font = SUB
    row += 1
    for text in [
        "Пункт 1 первый не из вежливости. По договору товар без "
        "согласованной цены не считается проданным: если погрузить "
        "такую позицию, за нее не заплатят, а назад она не поедет.",
        "Пункт 3 решает, влезет ли груз в один слой. Справочные массы "
        "задвижек уже оказались завышены почти вдвое — клинкет Ду300 "
        "весит 192 кг вместо 300 по справочнику. Если и габариты "
        "завышены, в контейнер войдет больше и останется запас.",
        "Этапы 2 и 3 не ждут первого: отбирать и паковать можно сразу, "
        "это самая долгая часть.",
        "Контейнер заказываем после замеров, иначе рискуем заказать "
        "корпус, в который груз не укладывается.",
        "Документы заполняются в день погрузки. Все прошлые расхождения "
        "в учете — именно от того, что отгрузку заносили потом.",
    ]:
        cell = ws.cell(row=row, column=1, value="— " + text)
        cell.font = BASE
        cell.alignment = Alignment(wrap_text=True, vertical="top")
        ws.row_dimensions[row].height = 30
        row += 1

    widths(ws, [6, 78, 16, 16, 40, 36, 12])

    OUT.mkdir(parents=True, exist_ok=True)
    path = OUT / "План_отгрузки_Питер_по_шагам.xlsx"
    wb.save(path)
    print(f"готово: {path}\n")
    k = 0
    for stage, steps in PLAN:
        print(stage)
        for what, who, when, _, _ in steps:
            k += 1
            print(f"  {k:>2}. [{who}, {when}] {what[:88]}")
    print(f"\nвсего шагов: {k}")


if __name__ == "__main__":
    main()
