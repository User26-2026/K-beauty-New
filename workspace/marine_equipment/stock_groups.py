#!/usr/bin/env python3
"""Товарные группы складского остатка.

На складе лежит не только арматура: электрика, насосы, сепараторы,
корпусная часть, блокформы, камбузные плиты. Для арматуры берем
готовый разбор по типам из build_spb_list_xlsx (клинкеты, фланцевая
проходная и так далее), для остального заводим свои группы.

Группа верхнего уровня отвечает на вопрос «что у нас за товар», а
подгруппа — «какой именно». По верхнему уровню считается сводка, по
подгруппе видно, из чего она набрана.
"""

import re
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from build_spb_list_xlsx import group_of  # noqa: E402

ARMATURE = "Арматура судовая"

# Не-арматура. Порядок важен: проверяется сверху вниз, первое
# совпадение выигрывает.
# Признаки запчасти. Слово «клапан» сюда намеренно не входит: сам по
# себе клапан — это арматура, запчастью его делает только раздел ЗИП
# или привязка к двигателю, и это ловится через подгруппу листа.
ZIP_PARTS = (r"\bзип\b|запчаст|ремкомплект|рем\.\s*комплект|вкладыш|"
             r"поршн|форсунк|распылител|плунжер|шатун|коленвал|гильз|"
             r"втулк|сальник|подшипник|прокладк|маслосъемн|"
             r"кольц\w*\s+(поршнев|уплотн)|тарелк\w*\s+сепарат|"
             r"ротор\w*\s+сепарат|барабан\w*\s+сепарат|"
             r"крышк\w*\s+цилиндра|блок\s+цилиндров|головка\s+блока")

RULES = [
    # ЗИП проверяется первым: «вкладыш к насосу» — запчасть, а не насос,
    # «тарелки сепаратора» — запчасть, а не сепаратор.
    (ZIP_PARTS, "ЗИП и запчасти", "Запчасти к оборудованию"),
    # Сетки и блины — запчасти к арматуре, а не фильтры и задвижки.
    # Проверяются ДО разбора по типам: иначе «сетка на фильтр Ду100»
    # попадет в фильтры забортной воды и при вычете отгруженного
    # спишется вместо настоящего фильтра.
    (r"сетк\w*\s*(на|к)\s*фильтр|блин\w*\s*к\s*клинкет|"
     r"шток\b|клин\w*\s*к\s*задвижк", ARMATURE, "Запчасти к арматуре"),
    # Пожарные гайки Шторца, Ротта и Богданова — соединения рукавов,
    # а не штуцерная арматура, с которой их сводит разбор по типам.
    (r"гайка|гайки", ARMATURE, "Гайки пожарные и соединения"),
    (r"ствол пожарн", ARMATURE, "Стволы пожарные"),
    (r"компенсатор", ARMATURE, "Компенсаторы"),
    (r"^фланец|фланец свободн|^фланц", ARMATURE, "Фланцы"),
    # Фреоновый клапан — холодильная арматура, с судовым
    # электромагнитным его сводить нельзя.
    (r"фреонов", ARMATURE, "Клапаны фреоновые"),
    # Стекла к иллюминаторам — корпусная часть, а к светильникам —
    # электрика. Слово одно, товар разный, поэтому проверяем вместе с
    # тем, к чему стекло.
    (r"стекл\w*\s*(к\s*)?(иллюминатор|портов|окн)|"
     r"иллюминатор\w*\s*стекл", "Корпусная часть",
     "Двери, иллюминаторы, стекла"),
    (r"светильник|стекло к светильник|патрон|плафон", "Электрика",
     "Светильники и комплектующие"),
    (r"двигатель|электродвигател|щит|выключател|контактор|электропривод|"
     r"кабел|провод\b|автомат\b|пускател|трансформатор|аккумулятор",
     "Электрика", "Двигатели, щиты, кабель"),
    (r"насос|нцвс?\b|нцкг|эцну|цвс\b", "Насосы", "Насосы"),
    (r"сепаратор", "Сепараторы", "Сепараторы"),
    (r"плита\b|комфорк|камбуз", "Камбузное оборудование",
     "Плиты и комплектующие"),
    (r"блокформ", "Блокформы", "Блокформы"),
    (r"дверь|двер\w+\b|иллюминатор|иллюмингатор|створк|штормая|"
     r"штормов|крышка легкая|горловин|люк\b|трап\b",
     "Корпусная часть", "Двери, иллюминаторы, стекла"),
    (r"компрессор", "Прочее оборудование", "Компрессоры"),
    (r"противовес|гак\b|скоб|ротор|весы|трал|"
     r"брашпил|лебедк|кран-балка|якор|швартов",
     "Прочее оборудование", "Палубное и прочее"),
    (r"трубк", "Прочее оборудование", "Трубки"),
    # Барабан СЦ — это барабан сепаратора, запчасть, а не изделие.
    (r"барабан\s*сц|корпус барабана", "ЗИП и запчасти",
     "ЗИП: сепараторы СЦ"),
    (r"крышка вгн|крышка световая|задрайк|проницаемая|барашк",
     "Корпусная часть", "Крышки и задрайки"),
    (r"к плите|пкэ|посуда", "Камбузное оборудование",
     "Плиты и комплектующие"),
    (r"пульт|рнп-|реле\b|извещател|термометр|контроллер",
     "Электрика", "Приборы и автоматика"),
    (r"подруливающ|блок цилиндров|вентилятор|кранец",
     "Прочее оборудование", "Палубное и прочее"),
]

# Арматура, которую разбор по типам не опознал. Проверяется после
# group_of: там разложены клинкеты, фланцевая и штуцерная, фильтры и
# коробки, а здесь остальное — фланцы, пожарные гайки, компенсаторы.
ARM_RULES = [
    (r"фланец|фланц\w*\s+свободн", "Фланцы"),
    (r"гайка|гайки", "Гайки пожарные и соединения"),
    (r"компенсатор", "Компенсаторы"),
    (r"затвор", "Затворы поворотные"),
    (r"ствол пожарн", "Стволы пожарные"),
    (r"сетка на фильтр|блины к клинкет", "Запчасти к арматуре"),
    (r"клапан|клинкет|задвижк|кран\b|фильтр|захлопк|кингстон|"
     r"коробка\s*\d|колонка смотров", "Прочая арматура"),
]

# Подзаголовок листа, который сам говорит, что ниже идет ЗИП. В файлах
# менеджера разделы размечены именно так, и это надежнее названия
# позиции: «крышка» под заголовком ЗИП — запчасть, а не корпусная часть.
ZIP_HEADING = re.compile(r"\bзип\b|запчаст|ремкомплект", re.I)

# Пометки состояния, которые меняют цену и продаваемость.
FLAWED = re.compile(r"\bбрак\b|не\s*комплект|в разборе|разобранн|"
                    r"без штока|без клинь|без поплавка|бой\b|корпус\b", re.I)

# Явный брак. Его из остатка НЕ вычитаем: в перечне контейнера и в
# ранних отгрузках нет ни одной строки со словом «брак», состояние
# там только «новый» или «б/у». Некомплект и «в разборе» — другое
# дело, такие позиции в контейнере есть (Ду300 в разборе, Ду250 без
# штока, Ду50 без клиньев), их вычитаем как обычно.
BROKEN = re.compile(r"\bбрак\b", re.I)


def broken(name):
    """Брак, который заведомо не отгружали."""
    return bool(BROKEN.search(name))


# Раздел листа -> группа, когда по названию позиция не опознается.
# Это разметка самой менеджера, и она знает склад лучше любого правила.
BY_SECTION = [
    (r"зип|запчаст", "ЗИП и запчасти", "Запчасти к оборудованию"),
    (r"электрик", "Электрика", "Прочая электрика"),
    (r"насос", "Насосы", "Насосы"),
    (r"сепаратор", "Сепараторы", "Сепараторы"),
    (r"кор\w*сная часть", "Корпусная часть", "Двери, иллюминаторы, стекла"),
    (r"камбуз", "Камбузное оборудование", "Плиты и комплектующие"),
    (r"блокформ", "Блокформы", "Блокформы"),
    (r"арматура", ARMATURE, "Прочая арматура"),
]


def classify(name, section="", subgroup=""):
    """Группа и подгруппа позиции.

    Разметка листа учитывается наравне с названием: под разделом «ЗИП»
    любая строка — запчасть, как бы она ни называлась, а подзаголовком
    там идет модель оборудования, и без нее запчасть не продать.

    Порядок такой: сначала раздел ЗИП, потом название, потом арматура
    по типу, и только в конце раздел листа. Название сильнее раздела
    везде, кроме ЗИП: контакторы в файле менеджера стоят под
    заголовком «Судовая запорная арматура», но это электрика.
    """
    model = subgroup.strip() or section.strip()
    if ZIP_HEADING.search(section) or ZIP_HEADING.search(subgroup):
        # «ЗИП» в начале имени модели не повторяем: подгруппа и так
        # называется «ЗИП: ...», а «ЗИП: ЗИП (коморка цех)» не читается
        model = re.sub(r"^\s*зип\s*", "", model, flags=re.I).strip()
        return "ЗИП и запчасти", (f"ЗИП: {model}" if model else
                                  "Запчасти к оборудованию")
    low = f"{name} {subgroup}".lower()
    for pattern, group, sub in RULES:
        if re.search(pattern, low):
            return group, sub
    g = group_of(name)
    if g and g != "Без описания — уточнить":
        return ARMATURE, g
    for pattern, sub in ARM_RULES:
        if re.search(pattern, low):
            return ARMATURE, sub
    for pattern, group, sub in BY_SECTION:
        if re.search(pattern, f"{section} {subgroup}".lower()):
            return group, sub
    return "Прочее оборудование", "Не разобрано"


def flawed(name):
    """Брак, некомплект, разобранное — продается отдельно и дешевле."""
    return bool(FLAWED.search(name))


# Материал из названия. Нужен при вычете отгруженного: стальной
# клапан Ду40 и бронзовый клапан Ду40 — разный товар и разная цена,
# у конкурента стальная задвижка Ду200 стоит 40 000 против 150 000 за
# бронзовую. Сводить их друг с другом нельзя.
NOT_BRONZE = re.compile(r"\bстал[ьи]|\bст\.|титан|нержав|амг\b|"
                        r"алюмин", re.I)


def not_bronze(name):
    """Название прямо говорит, что это не бронза."""
    return bool(NOT_BRONZE.search(name))


DU = re.compile(r"\bд[уy]\s*\.?\s*(\d{1,3})", re.I)


def du_of(name):
    """Условный диаметр из названия. Только «Ду 100», не «д. 300»:
    у иллюминаторов «д.» — это диаметр стекла, а не арматурный Ду."""
    m = DU.search(name)
    return int(m.group(1)) if m else 0


DRAW = re.compile(r"\b\d{3}-[\dА-Яа-яA-Za-z.\-]{3,}")


def draw_of(name):
    """Номера чертежей из названия: их бывает несколько в одной строке."""
    return [re.sub(r"[\s,;)]+$", "", d) for d in DRAW.findall(name)]
