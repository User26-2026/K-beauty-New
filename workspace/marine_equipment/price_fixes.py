#!/usr/bin/env python3
"""Подтвержденные опечатки в ценах договора.

В приложениях цена местами записана с потерянным разрядом. Такие
записи видно по тому, что верх диапазона больше низа втрое и выше.
Исправления подтверждены собственником; исходный файл тоже надо
поправить, иначе при следующей выгрузке опечатка вернется.

Ключ — очищенное наименование, значение — цена в рублях.
"""

import re

# «Фильтр забортной воды Ду 100» записан как «55-650»: это 55-65 тысяч,
# потерян разряд. По верхней границе 65 000. Подтверждено 13.10.2026
FIXES = {
    "фильтр забортной воды ду 100": 65_000,
}


def clean(name):
    """Наименование к сопоставимому виду: без регистра, знаков и ё."""
    s = str(name or "").lower().replace("ё", "е")
    s = re.sub(r"[^а-я0-9]+", " ", s)
    return re.sub(r"\s+", " ", s).strip()


def fix(name):
    """Исправленная цена, если опечатка по этой позиции подтверждена."""
    return FIXES.get(clean(name))
