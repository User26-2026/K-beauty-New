#!/usr/bin/env python3
"""Паспортные массы арматуры из заводского справочника номенклатуры.

Источник — справочник номенклатуры трубопроводной арматуры, разделы
4.1.1 «Фильтр заборной воды фланцевый проходной сетчатый» (стр. 25-26)
и 4.12.1 «Задвижка клинкетная фланцевая двухдисковая» (стр. 393-395).
Это таблица завода с обозначениями, габаритами и массой, а не наша
прикидка.

Зачем это важно. Наш прежний справочник масс был выведен по форме
«масса растет как куб размера» и врал в обе стороны. Крупные задвижки
он завышал: Ду300 — 300 кг против паспортных 192 по латуни. Мелкие
занижал вдвое: Ду80 — 11,7 кг против 24. На складе 44 задвижки Ду80,
и это одна позиция с ошибкой в полтонны.

Два подтверждения, что паспорт прав, а наш справочник нет:

1. Веса в списке менеджера — Ду200 88, Ду250 125, Ду300 192, Ду350 228
   — совпадают с латунной строкой паспорта до килограмма. Значит это
   не замеры, а выписка из этого же справочника.
2. Отгруженные 45 клинкетов Ду150 весят по расписке 1 800 кг брутто,
   то есть 40 кг штука. Паспорт дает 41,8 по бронзе и 46,5 по латуни.
   Наш прежний справочник давал 85 — ровно вдвое больше.

Материал решает 10-15% массы: латунь тяжелее бронзы, углеродистая
сталь тяжелее обеих. Там, где материал в учете не указан (а это почти
везде), берем ЛАТУНЬ — она тяжелее бронзы, и для погрузки осторожнее
ошибиться в большую сторону, чем перегрузить контейнер.
"""

# Задвижка клинкетная фланцевая двухдисковая, раздел 4.12.1.
# Ключ — условный диаметр, значение — масса одной штуки в килограммах.
GATE_BRONZE = {50: 10.5, 65: 17.9, 80: 21.9, 100: 28.3, 125: 37.2,
               150: 41.8, 200: 76.5, 250: 115.8, 300: 167.4, 350: 212.5}
GATE_BRASS = {65: 17.1, 80: 24.0, 100: 32.0, 150: 46.5, 200: 88.0,
              250: 125.0, 300: 192.0, 350: 228.0}
# углеродистая сталь, Ру16 — заметно тяжелее цветной
GATE_STEEL = {50: 17.0, 80: 27.0, 100: 48.0, 150: 98.0, 200: 138.0}

# Фильтр заборной воды фланцевый проходной сетчатый, раздел 4.1.1.
# Основной ряд 1ФЗВ, Ру4, медно-никелевый сплав.
FILTER = {40: 11.0, 50: 14.0, 80: 27.0, 100: 45.0, 125: 47.0, 150: 64.0,
          200: 148.3, 250: 171.4, 300: 192.0, 350: 287.0}
# бронзовые и высокого давления идут отдельной строкой и тяжелее:
# Ду40 Ру40 бронза — 44 кг, Ду150 Ру6 бронза (ФВ 150/6-4,5) — 100 кг
FILTER_BRONZE = {40: 44.0, 150: 100.0}


def gate(du, material=""):
    """Масса задвижки по диаметру и материалу, если он известен."""
    m = (material or "").lower()
    if "сталь" in m and du in GATE_STEEL:
        return GATE_STEEL[du]
    if "бронз" in m and du in GATE_BRONZE:
        return GATE_BRONZE[du]
    # материал не назван — считаем по латуни, она тяжелее бронзы
    return GATE_BRASS.get(du) or GATE_BRONZE.get(du)


def filter_weight(du, ru=None, material=""):
    """Масса фильтра забортной воды по диаметру."""
    m = (material or "").lower()
    if ("бронз" in m or (ru and ru >= 6)) and du in FILTER_BRONZE:
        return FILTER_BRONZE[du]
    return FILTER.get(du)


# Сведенная таблица для справочника масс: один вес на диаметр, по
# латуни там, где она есть. Промежуточные Ду60 и Ду70 паспорта не
# имеют, они интерполированы между соседними строками и помечены.
GATE_TABLE = {d: max(GATE_BRONZE.get(d, 0), GATE_BRASS.get(d, 0))
              for d in set(GATE_BRONZE) | set(GATE_BRASS)}
GATE_TABLE[60] = 14.0   # интерполяция между Ду50 и Ду65
GATE_TABLE[70] = 20.0   # интерполяция между Ду65 и Ду80
INTERPOLATED = (60, 70)
