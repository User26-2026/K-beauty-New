def bounds(value):
    """Границы цены: одно число или диапазон, в рублях."""
    if isinstance(value, (int, float)):
        return [int(value)]
    return [int(n.replace(" ", "").replace("\u00a0", ""))
            for n in re.findall(r"\d+(?:[  ]\d{3})*", str(value or ""))]


def money(lo, hi):
    """Сумма одним числом или диапазоном."""
    fmt = lambda v: f"{v:,.0f}".replace(",", " ")  # noqa: E731
    return fmt(lo) if lo == hi else f"{fmt(lo)} - {fmt(hi)}"


def price(item):
    """Цена за единицу: от веса по ставке за килограмм или из
    спецификации, как она там записана."""
    if item.get("rate"):
        return money(*(2 * [round(item["kg"] * item["rate"])]))
    return str(item["price"])


def total(s):
    """Сумма по партии. Диапазон в цене дает диапазон в сумме."""
    lo = hi = 0
    for i in s["items"]:
        b = bounds(price(i))
        lo += min(b) * i["qty"]
        hi += max(b) * i["qty"]
    return money(lo, hi)


