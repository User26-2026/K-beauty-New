def price(item):
    """Цена за единицу: прямая или от веса по ставке за килограмм."""
    if item.get("rate"):
        return round(item["kg"] * item["rate"])
    return item["price"]


def total(s):
    return sum(i["qty"] * price(i) for i in s["items"])


