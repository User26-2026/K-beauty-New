#!/usr/bin/env python3
"""Цены металлоприемки и закупочная цена от них.

Прайс приемки на 13.10.2026, снят с сайта приемщика. На сайте цены
даны за ТОННУ по цветному металлу и за килограмм по черному лому и
нихрому — здесь все приведено к рублям за килограмм.

ЗАКУПОЧНАЯ ЦЕНА = ЦЕНА ЛОМА * 2,5. Договоренность с Антоном Бурыкиным
от 25.10.2026. Отсюда же берется и ставка на бронзу: 745 * 2,5 =
1 862,50 руб за килограмм, та самая, по которой посчитана керченская
партия и бронза в приложении 4.

Множитель один на все материалы, поэтому цена считается и по стали, и
по титану, и по алюминию — а не только по бронзе, как было раньше.

Лом остается нижней границей цены: любая позиция стоит хотя бы как
лом, и ниже продавать незачем — сдать быстрее и без споров по
состоянию.
"""

# руб за килограмм, прайс приемки на 13.10.2026
SCRAP = {
    "медь": 945,
    "бронза": 745,
    "латунь": 635,
    "нихром": 1_342,
    "алюминий": 260,
    "титан": 130,
    "цам": 130,
    "свинец": 70,
    "нержавейка": 60,
    "аккумуляторы": 35,
    "трансформаторы": 20,
    "черный металл": 19,
    "чугун": 19,
    "сталь": 19,
    "электродвигатели": 15,
}

# во сколько раз закупочная цена выше лома
MULTIPLIER = 2.5

# как наш материал из учета ложится на ставку приемки. Класс
# «бронза/латунь» считаем ПО БРОНЗЕ: собственник назначил ставку
# 1 862,50, а это ровно бронза, умноженная на множитель.
BY_MATERIAL = {
    "бронза/латунь": SCRAP["бронза"],
    "бронза": SCRAP["бронза"],
    "латунь": SCRAP["латунь"],
    "медь": SCRAP["медь"],
    "алюминий": SCRAP["алюминий"],
    "титан": SCRAP["титан"],
    "нержавейка": SCRAP["нержавейка"],
    "сталь": SCRAP["сталь"],
    "чугун": SCRAP["чугун"],
}

BRONZE = SCRAP["бронза"]
BRASS = SCRAP["латунь"]


def rate(material_name):
    """Ставка приемки за килограмм по нашему материалу."""
    return BY_MATERIAL.get(material_name, SCRAP["сталь"])


def value(material_name, kg):
    """Сколько дадут за позицию на приемке."""
    r = rate(material_name)
    return r * kg if r else None


def purchase_rate(material_name):
    """Закупочная цена за килограмм: лом, умноженный на множитель."""
    r = rate(material_name)
    return r * MULTIPLIER if r else None


def purchase(material_name, kg):
    """Закупочная цена позиции."""
    r = purchase_rate(material_name)
    return r * kg if r else None
