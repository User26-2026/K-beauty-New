#!/usr/bin/env python3
"""Цены металлоприемки: нижняя граница, ниже которой продавать незачем.

Любая позиция всегда стоит хотя бы как лом. Если предложение покупателя
ниже лома, позицию проще сдать: это и быстрее, и без споров по
состоянию и комплектности.

Ставки на 13.10.2026, руб за килограмм. Для бронзы и латуни считаем по
латуни: в учете материал почти нигде не разделен, а латунь дешевле, то
есть оценка получается осторожной. По бронзе граница выше, 600.

Титана в списке нет, ставку надо запросить отдельно.
"""

SCRAP = {
    "медь": 900,
    "бронза": 600,
    "латунь": 500,
    "алюминий": 95,
    "нержавейка": 25,
    "чугун": 9,
    "сталь": 9,
}

# как наш материал из учета ложится на ставку приемки
BY_MATERIAL = {
    "бронза/латунь": SCRAP["латунь"],   # осторожно, по латуни
    "нержавейка": SCRAP["нержавейка"],
    "сталь": SCRAP["сталь"],
    "титан": None,                      # ставки нет, запросить
}

BRONZE = SCRAP["бронза"]
BRASS = SCRAP["латунь"]


def rate(material_name):
    """Ставка приемки за килограмм по нашему материалу."""
    return BY_MATERIAL.get(material_name, SCRAP["сталь"])


def value(material_name, kg):
    """Сколько дадут за позицию на приемке."""
    r = rate(material_name)
    return r * kg if r else None
