#!/usr/bin/env python3
"""Примерная стоимость ремонта арматуры по типу и диаметру.

Прайс прислан собственником 15.10.2026. Это ориентир мастерской, а не
счет: фактическая стоимость ставится по факту выполненного ремонта.

Ремонт в цену по договору не входит. Он нужен, чтобы понимать, сколько
стоит довести позицию до товарного вида перед продажей, и чтобы
сравнивать «продать как есть» с «отремонтировать и продать дороже».

Прайс разделен не по типу изделия, а по присоединению: штуцерные,
фланцевые, и отдельно клинкетные задвижки. Поэтому штуцерные краны
считаются по штуцерному ряду — работа там та же, что по штуцерному
клапану того же диаметра.

Фильтров, клапанных коробок, захлопок, кингстонов и вентиляционных
головок в прайсе нет — по ним стоимость ремонта запрашивается
отдельно.
"""

# тип -> диаметр -> рубли за единицу
PRICES = {
    "клапан штуцерный": {6: 2_500, 10: 2_500, 15: 3_000, 20: 3_500,
                         25: 4_000, 32: 4_500},
    "клапан фланцевый": {20: 4_500, 25: 4_500, 32: 5_000, 40: 5_000,
                         50: 5_500, 65: 6_000, 80: 6_000, 100: 6_500,
                         125: 7_000, 150: 8_000, 200: 12_000,
                         250: 15_000, 300: 20_000, 350: 25_000},
    "клинкет/задвижка": {50: 7_500, 65: 8_500, 80: 10_000, 100: 12_000,
                         125: 15_000, 150: 18_000, 200: 20_000,
                         250: 25_000, 300: 28_000, 350: 30_000},
}

# состояния, при которых ремонт не нужен
NEW = ("новый", "новая", "new")


def is_new(condition):
    c = (condition or "").strip().lower().rstrip("?").strip()
    return c.startswith(NEW)


def price(kind, du, condition=None):
    """Стоимость ремонта единицы или None, если прайс ее не покрывает.

    Новое не ремонтируем. Если точного диаметра в прайсе нет, берется
    ближайший: ряд идет с шагом, и между Ду60 и Ду65 разницы в работе
    практически никакой.
    """
    if is_new(condition):
        return None
    table = PRICES.get(kind)
    if not table or not du:
        return None
    if du in table:
        return table[du]
    return table[min(table, key=lambda x: abs(x - du))]
