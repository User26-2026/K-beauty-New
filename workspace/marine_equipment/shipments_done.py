def cost(s):
    """Сколько стоила отгрузка по расписке."""
    return sum(v for _, v in s["services"])


def units(s):
    return sum(i["qty"] for i in s["items"])


def per_unit(s):
    return cost(s) / units(s) if units(s) else 0


def per_kg(s):
    return cost(s) / s["kg"] if s["kg"] else 0


def unit_weight(s):
    """Вес одной единицы по расписке, брутто — вместе с тарой."""
    return s["kg"] / units(s) if units(s) else 0


def shipped_off():
    """Сколько штук снять с наличия: позиция и локация -> количество."""
    out = {}
    for s in SHIPMENTS:
        for i in s["items"]:
            key = (i["registry"], i["location"])
            out[key] = out.get(key, 0) + i["qty"]
    return out
