def style_header(ws, row, ncols):
    for c in range(1, ncols + 1):
        cell = ws.cell(row=row, column=c)
        cell.fill = HEAD_FILL
        cell.font = HEAD_FONT
        cell.alignment = Alignment(vertical="center", wrap_text=True)
        cell.border = BORDER
    ws.row_dimensions[row].height = 30


def set_widths(ws, widths):
    for i, w in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(i)].width = w


def sheet_plan(wb):
    ws = wb.create_sheet("План действий")
    ws["A1"] = "План действий, сентябрь-октябрь 2026"
    ws["A1"].font = TITLE_FONT
    ws["A2"] = ("Заполняйте только желтую колонку «Статус» — выбор из списка. "
                "Остальное собирается генератором build_plan_xlsx.py.")
    ws["A2"].font = NOTE_FONT

    headers = ["№", "Неделя", "Срок", "Направление", "Задача",
               "Ответственный", "Статус", "Комментарий"]
    start = 4
    for i, h in enumerate(headers, start=1):
        ws.cell(row=start, column=i, value=h)
    style_header(ws, start, len(headers))

    for n, (week, term, flow, task, who, note) in enumerate(PLAN, start=1):
        row = start + n
        values = [n, week, term, flow, task, who, "Не начато", note]
        for i, v in enumerate(values, start=1):
            cell = ws.cell(row=row, column=i, value=v)
            cell.font = BASE_FONT
            cell.border = BORDER
            cell.alignment = Alignment(vertical="top", wrap_text=(i in (5, 8)))
            if i <= 4:
                cell.fill = WEEK_FILLS.get(week, WEEK_FILLS["Постоянно"])
        ws.cell(row=row, column=7).fill = INPUT_FILL

    last = start + len(PLAN)
    dv = DataValidation(type="list", formula1='"%s"' % ",".join(STATUSES),
                        allow_blank=True)
    ws.add_data_validation(dv)
    dv.add(f"G{start + 1}:G{last}")

    # сводка по статусам считается формулами, а не в питоне
    s = last + 2
    ws.cell(row=s, column=4, value="Сводка").font = Font(name=FONT, bold=True)
    ws.cell(row=s, column=5, value="Всего задач").font = BASE_FONT
    ws.cell(row=s, column=6, value=f"=COUNTA(E{start + 1}:E{last})").font = BASE_FONT
    for i, status in enumerate(STATUSES, start=1):
        ws.cell(row=s + i, column=5, value=status).font = BASE_FONT
        ws.cell(row=s + i, column=6,
                value=f'=COUNTIF(G{start + 1}:G{last},"{status}")').font = BASE_FONT
    ws.cell(row=s + len(STATUSES) + 1, column=5, value="Готовность").font = BASE_FONT
    done = s + 3
    cell = ws.cell(row=s + len(STATUSES) + 1, column=6,
                   value=f"=IFERROR(F{done}/F{s},0)")
    cell.number_format = "0%"
    cell.font = Font(name=FONT, bold=True)

    ws.auto_filter.ref = f"A{start}:H{last}"
    ws.freeze_panes = f"A{start + 1}"
    set_widths(ws, [5, 12, 14, 17, 58, 20, 14, 46])
    return ws


